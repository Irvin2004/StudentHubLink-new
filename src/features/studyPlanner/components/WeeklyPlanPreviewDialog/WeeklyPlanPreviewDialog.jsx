import { useMemo, useState } from "react";

import Button from "../../../../components/ui/Button/index.js";
import Input from "../../../../components/ui/Input/index.js";
import Modal from "../../../../components/ui/Modal/index.js";
import Select from "../../../../components/ui/Select/index.js";
import styles from "./WeeklyPlanPreviewDialog.module.css";

function linkedLabel(block) {
    if (block.quizId) return "Linked quiz";
    if (block.flashcardDeckId) return "Linked flashcard deck";
    if (block.resourceId) return "Linked resource";
    return "Subject focus";
}

function formatMinutes(minutes) {
    const value = Math.max(0, Number(minutes) || 0);
    if (value < 60) return `${value} min`;
    const hours = Math.floor(value / 60);
    const remainder = value % 60;
    return remainder ? `${hours}h ${remainder}m` : `${hours}h`;
}

export default function WeeklyPlanPreviewDialog({
    onClose,
    onSave,
    open,
    plan
}) {
    const [blocks, setBlocks] = useState(() => plan?.blocks || []);
    const [editingId, setEditingId] = useState(null);
    const [error, setError] = useState("");
    const [saving, setSaving] = useState(false);
    const selectedBlocks = blocks.filter(
        (block) => !block.existing && block.selected
    );
    const days = useMemo(
        () =>
            (plan?.days || []).map((day) => ({
                ...day,
                blocks: blocks.filter((block) => block.dueDate === day.date)
            })),
        [blocks, plan?.days]
    );
    const overloadedDays = days.filter((day) => {
        const existingMinutes = day.blocks
            .filter((block) => block.existing)
            .reduce((total, block) => total + Number(block.duration), 0);
        const selectedMinutes = day.blocks
            .filter((block) => block.existing || block.selected)
            .reduce((total, block) => total + Number(block.duration), 0);
        return (
            selectedMinutes >
            Math.max(plan?.summary.dailyCap || 0, existingMinutes)
        );
    });

    function updateBlock(blockId, field, value) {
        setBlocks((current) =>
            current.map((block) =>
                block.id === blockId ? { ...block, [field]: value } : block
            )
        );
    }

    function toggleBlock(blockId) {
        setBlocks((current) =>
            current.map((block) =>
                block.id === blockId
                    ? { ...block, selected: !block.selected }
                    : block
            )
        );
    }

    async function handleSave() {
        setError("");
        setSaving(true);
        try {
            await onSave(
                selectedBlocks.map((block) => ({
                    dueDate: block.dueDate,
                    estimatedMinutes: Number(block.duration),
                    flashcardDeckId: block.flashcardDeckId,
                    notes: `Generated by Thuto: ${block.reason}`.slice(0, 500),
                    priority: block.priority,
                    quizId: block.quizId,
                    resourceId: block.resourceId,
                    subject: block.subject,
                    taskType: block.taskType,
                    title: block.title
                }))
            );
        } catch (nextError) {
            setError(
                nextError?.message || "The weekly plan could not be saved."
            );
        } finally {
            setSaving(false);
        }
    }

    return (
        <Modal
            description="Review Thuto’s proposed seven-day schedule. Nothing is saved until you accept it."
            onClose={saving ? undefined : onClose}
            open={open}
            size="wide"
            title="Your week with Thuto"
        >
            <div className={styles.preview}>
                <div className={styles.summary}>
                    <div>
                        <span>Available this week</span>
                        <strong>
                            {formatMinutes(plan?.summary.availableMinutes)}
                        </strong>
                    </div>
                    <div>
                        <span>Already planned</span>
                        <strong>
                            {formatMinutes(plan?.summary.existingMinutes)}
                        </strong>
                    </div>
                    <div>
                        <span>Thuto proposes</span>
                        <strong>
                            {formatMinutes(
                                selectedBlocks.reduce(
                                    (total, block) =>
                                        total + Number(block.duration),
                                    0
                                )
                            )}
                        </strong>
                    </div>
                </div>

                <p className={styles.safeguard}>
                    Existing tasks stay fixed. Thuto limits new work to about{" "}
                    {formatMinutes(plan?.summary.dailyCap)} per day and gives
                    urgent or weaker topics the earliest safe spaces.
                </p>

                <div className={styles.days}>
                    {days.map((day) => {
                        const includedMinutes = day.blocks
                            .filter((block) => block.existing || block.selected)
                            .reduce(
                                (total, block) =>
                                    total + Number(block.duration),
                                0
                            );
                        return (
                            <section className={styles.day} key={day.date}>
                                <header>
                                    <div>
                                        <h3>{day.dayLabel}</h3>
                                        <span>{day.date}</span>
                                    </div>
                                    <strong>
                                        {formatMinutes(includedMinutes)}
                                    </strong>
                                </header>
                                {day.blocks.length ? (
                                    <div className={styles.blocks}>
                                        {day.blocks.map((block) => (
                                            <article
                                                className={`${styles.block} ${
                                                    !block.existing &&
                                                    !block.selected
                                                        ? styles.skipped
                                                        : ""
                                                }`}
                                                key={block.id}
                                            >
                                                <div
                                                    className={styles.blockTop}
                                                >
                                                    <div>
                                                        <span
                                                            className={
                                                                styles.badge
                                                            }
                                                        >
                                                            {block.existing
                                                                ? "Already planned"
                                                                : block.priority}
                                                        </span>
                                                        <h4>{block.title}</h4>
                                                    </div>
                                                    {!block.existing ? (
                                                        <div
                                                            className={
                                                                styles.blockActions
                                                            }
                                                        >
                                                            <Button
                                                                onClick={() =>
                                                                    setEditingId(
                                                                        editingId ===
                                                                            block.id
                                                                            ? null
                                                                            : block.id
                                                                    )
                                                                }
                                                                size="small"
                                                                variant="secondary"
                                                            >
                                                                {editingId ===
                                                                block.id
                                                                    ? "Done"
                                                                    : "Edit"}
                                                            </Button>
                                                            <Button
                                                                aria-pressed={
                                                                    !block.selected
                                                                }
                                                                onClick={() =>
                                                                    toggleBlock(
                                                                        block.id
                                                                    )
                                                                }
                                                                size="small"
                                                                variant="outline"
                                                            >
                                                                {block.selected
                                                                    ? "Skip"
                                                                    : "Include"}
                                                            </Button>
                                                        </div>
                                                    ) : null}
                                                </div>

                                                {editingId === block.id ? (
                                                    <div
                                                        className={
                                                            styles.editor
                                                        }
                                                    >
                                                        <Input
                                                            label="Task"
                                                            onChange={(event) =>
                                                                updateBlock(
                                                                    block.id,
                                                                    "title",
                                                                    event.target
                                                                        .value
                                                                )
                                                            }
                                                            required
                                                            value={block.title}
                                                        />
                                                        <Input
                                                            label="Subject"
                                                            onChange={(event) =>
                                                                updateBlock(
                                                                    block.id,
                                                                    "subject",
                                                                    event.target
                                                                        .value
                                                                )
                                                            }
                                                            required
                                                            value={
                                                                block.subject
                                                            }
                                                        />
                                                        <Input
                                                            label="Date"
                                                            max={
                                                                plan.days.at(-1)
                                                                    .date
                                                            }
                                                            min={
                                                                plan.days[0]
                                                                    .date
                                                            }
                                                            onChange={(event) =>
                                                                updateBlock(
                                                                    block.id,
                                                                    "dueDate",
                                                                    event.target
                                                                        .value
                                                                )
                                                            }
                                                            required
                                                            type="date"
                                                            value={
                                                                block.dueDate
                                                            }
                                                        />
                                                        <Input
                                                            label="Duration (minutes)"
                                                            max="120"
                                                            min="15"
                                                            onChange={(event) =>
                                                                updateBlock(
                                                                    block.id,
                                                                    "duration",
                                                                    Number(
                                                                        event
                                                                            .target
                                                                            .value
                                                                    )
                                                                )
                                                            }
                                                            required
                                                            step="5"
                                                            type="number"
                                                            value={
                                                                block.duration
                                                            }
                                                        />
                                                        <Select
                                                            label="Priority"
                                                            onChange={(event) =>
                                                                updateBlock(
                                                                    block.id,
                                                                    "priority",
                                                                    event.target
                                                                        .value
                                                                )
                                                            }
                                                            value={
                                                                block.priority
                                                            }
                                                        >
                                                            <option value="Low">
                                                                Low
                                                            </option>
                                                            <option value="Medium">
                                                                Medium
                                                            </option>
                                                            <option value="High">
                                                                High
                                                            </option>
                                                        </Select>
                                                    </div>
                                                ) : null}

                                                <dl className={styles.details}>
                                                    <div>
                                                        <dt>Subject</dt>
                                                        <dd>{block.subject}</dd>
                                                    </div>
                                                    <div>
                                                        <dt>Duration</dt>
                                                        <dd>
                                                            {formatMinutes(
                                                                block.duration
                                                            )}
                                                        </dd>
                                                    </div>
                                                    <div>
                                                        <dt>Study material</dt>
                                                        <dd>
                                                            {linkedLabel(block)}
                                                        </dd>
                                                    </div>
                                                </dl>
                                                <p>{block.reason}</p>
                                            </article>
                                        ))}
                                    </div>
                                ) : (
                                    <p className={styles.rest}>
                                        Open study time
                                    </p>
                                )}
                            </section>
                        );
                    })}
                </div>

                {overloadedDays.length ? (
                    <p className={styles.error} role="alert">
                        One of your edits overloads a day. Reduce its duration,
                        move it, or skip it before saving.
                    </p>
                ) : null}
                {error ? (
                    <p className={styles.error} role="alert">
                        {error}
                    </p>
                ) : null}

                <div className={styles.footer}>
                    <Button
                        disabled={saving}
                        onClick={onClose}
                        variant="secondary"
                    >
                        Keep current plan
                    </Button>
                    <Button
                        disabled={
                            !selectedBlocks.length || overloadedDays.length > 0
                        }
                        loading={saving}
                        loadingLabel="Saving week"
                        onClick={handleSave}
                    >
                        Accept all
                    </Button>
                </div>
            </div>
        </Modal>
    );
}

test("previews, edits, skips, and accepts a Thuto weekly plan", async () => {
    plannerActions.addTasks.mockClear();
    renderPlanner();

    fireEvent.click(
        screen.getByRole("button", {
            name: "Generate My Week with Thuto"
        })
    );

    const dialog = screen.getByRole("dialog", {
        name: "Your week with Thuto"
    });
    expect(
        within(dialog).getAllByText("Already planned").length
    ).toBeGreaterThan(1);
    expect(within(dialog).getByText("Retake Biology Quiz")).toBeVisible();
    expect(within(dialog).getByText("Study Chapter 4 notes")).toBeVisible();

    const quizBlock = within(dialog)
        .getByText("Retake Biology Quiz")
        .closest("article");
    fireEvent.click(within(quizBlock).getByRole("button", { name: "Edit" }));
    fireEvent.change(
        within(quizBlock).getByLabelText(/^Duration \(minutes\)/),
        {
            target: { value: "45" }
        }
    );

    const resourceBlock = within(dialog)
        .getByText("Study Chapter 4 notes")
        .closest("article");
    fireEvent.click(
        within(resourceBlock).getByRole("button", { name: "Skip" })
    );
    fireEvent.click(within(dialog).getByRole("button", { name: "Accept all" }));

    await vi.waitFor(() => expect(plannerActions.addTasks).toHaveBeenCalled());
    const savedBlocks = plannerActions.addTasks.mock.calls[0][0];
    expect(savedBlocks).toEqual(
        expect.arrayContaining([
            expect.objectContaining({
                estimatedMinutes: 45,
                quizId: "quiz-1",
                taskType: "quiz",
                title: "Retake Biology Quiz"
            })
        ])
    );
    expect(savedBlocks.some((block) => block.resourceId)).toBe(false);
    await vi.waitFor(() =>
        expect(
            screen.queryByRole("dialog", { name: "Your week with Thuto" })
        ).not.toBeInTheDocument()
    );
});

test("detects a plan needing attention and applies only approved re-plan changes", async () => {
    plannerActions.applyReplan.mockClear();
    renderPlanner();

    expect(
        screen.getByText("Thuto says your plan needs attention")
    ).toBeVisible();
    fireEvent.click(
        screen.getByRole("button", { name: "Review an updated plan" })
    );

    const dialog = screen.getByRole("dialog", { name: "Re-plan my week" });
    const missedReason = within(dialog).getByText(
        /because the original block was missed/
    );
    const movedChange = missedReason.closest("article");
    fireEvent.click(
        within(movedChange).getByRole("button", { name: "Skip change" })
    );
    fireEvent.click(
        within(dialog).getByRole("button", {
            name: "Approve selected changes"
        })
    );

    await vi.waitFor(() =>
        expect(plannerActions.applyReplan).toHaveBeenCalled()
    );
    expect(
        plannerActions.applyReplan.mock.calls[0][0].some(
            (change) => change.taskId === "overdue-active"
        )
    ).toBe(false);
});

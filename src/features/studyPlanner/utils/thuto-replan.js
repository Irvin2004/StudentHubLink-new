import { generateThutoWeeklyPlan } from "./thuto-weekly-plan.js";

const THUTO_NOTE_PREFIX = "Generated by Thuto:";

function dateKey(date) {
    return [
        date.getFullYear(),
        String(date.getMonth() + 1).padStart(2, "0"),
        String(date.getDate()).padStart(2, "0")
    ].join("-");
}

function timestampValue(value) {
    if (typeof value?.toMillis === "function") return value.toMillis();
    if (typeof value?.toDate === "function") return value.toDate().getTime();
    if (value instanceof Date) return value.getTime();
    const result = new Date(value || 0).getTime();
    return Number.isFinite(result) ? result : 0;
}

function blockKey(item) {
    if (item.quizId) return `quiz:${item.quizId}`;
    if (item.flashcardDeckId) return `flashcards:${item.flashcardDeckId}`;
    if (item.resourceId) return `resource:${item.resourceId}`;
    const subject = String(item.subject || "")
        .trim()
        .toLowerCase();
    const title = String(item.title || "")
        .trim()
        .toLowerCase();
    const titleFocus = title.replace(/^(review|revise|refresh)\s+/, "");
    if (
        subject &&
        titleFocus &&
        titleFocus !== subject &&
        title !== titleFocus
    ) {
        return `concept:${title}`;
    }
    return `topic:${subject || title}`;
}

function toTask(block) {
    return {
        dueDate: block.dueDate,
        estimatedMinutes: Number(block.duration ?? block.estimatedMinutes),
        flashcardDeckId: block.flashcardDeckId,
        notes:
            block.notes ||
            `${THUTO_NOTE_PREFIX} ${block.reason || "Revised weekly plan."}`,
        priority: block.priority || "Medium",
        quizId: block.quizId,
        resourceId: block.resourceId,
        subject: block.subject || "General",
        taskType: block.taskType || "study",
        title: block.title
    };
}

function dayName(value) {
    return new Date(`${value}T00:00:00`).toLocaleDateString(undefined, {
        weekday: "long"
    });
}

export function isThutoPlannedTask(task) {
    return String(task?.notes || "").startsWith(THUTO_NOTE_PREFIX);
}

export function detectThutoPlanAttention(
    { memoryTopics = [], plannerTasks = [], quizzes = [], dailyCap = 60 } = {},
    now = new Date()
) {
    const today = dateKey(now);
    const generated = plannerTasks.filter(isThutoPlannedTask);
    if (!generated.length) return { needsAttention: false, reasons: [] };

    const reasons = [];
    const active = plannerTasks.filter((task) => !task.completed);
    if (generated.some((task) => !task.completed && task.dueDate < today)) {
        reasons.push("A Thuto study block was missed.");
    }
    if (
        active.some(
            (task) =>
                task.dueDate &&
                active
                    .filter((item) => item.dueDate === task.dueDate)
                    .reduce(
                        (total, item) =>
                            total + Number(item.estimatedMinutes || 0),
                        0
                    ) > dailyCap
        )
    ) {
        reasons.push("One or more planner days are overloaded.");
    }
    if (
        plannerTasks.some(
            (task) => task.completed && task.dueDate && task.dueDate > today
        )
    ) {
        reasons.push("Finishing work early opened new study time.");
    }

    const planTimestamp = Math.max(
        ...generated.map((task) =>
            Math.max(
                timestampValue(task.createdAt),
                timestampValue(task.updatedAt)
            )
        ),
        0
    );
    if (
        planTimestamp &&
        active.some(
            (task) =>
                !isThutoPlannedTask(task) &&
                timestampValue(task.createdAt) > planTimestamp
        )
    ) {
        reasons.push("A new deadline was added after this plan was created.");
    }
    if (
        planTimestamp &&
        (memoryTopics.some(
            (topic) => timestampValue(topic.updatedAt) > planTimestamp
        ) ||
            quizzes.some((quiz) =>
                (quiz.attempts || []).some(
                    (attempt) =>
                        timestampValue(
                            attempt.completedAt || attempt.submittedAt
                        ) > planTimestamp
                )
            ))
    ) {
        reasons.push(
            "Your latest performance changed your learning priorities."
        );
    }

    return { needsAttention: reasons.length > 0, reasons };
}

export function generateThutoReplan(inputs = {}, now = new Date()) {
    const plannerTasks = inputs.plannerTasks || [];
    const currentBlocks = plannerTasks.filter(
        (task) => isThutoPlannedTask(task) && !task.completed
    );
    const fixedTasks = plannerTasks.filter((task) => !isThutoPlannedTask(task));
    const target = generateThutoWeeklyPlan(
        { ...inputs, plannerTasks: fixedTasks },
        now
    );
    const proposed = target.blocks.filter((block) => !block.existing);
    const unmatched = new Map(
        currentBlocks.map((task) => [blockKey(task), task])
    );
    const today = dateKey(now);
    const changes = [];

    proposed.forEach((block) => {
        const key = blockKey(block);
        const current = unmatched.get(key);
        const after = toTask(block);
        if (!current) {
            changes.push({
                after,
                id: `add:${block.id}`,
                kind: "add",
                reason: `Added ${after.estimatedMinutes} minutes of ${after.subject} because ${block.reason.toLowerCase()}`,
                selected: true
            });
            return;
        }
        unmatched.delete(key);

        if (current.dueDate < today && Number(current.estimatedMinutes) >= 60) {
            const firstMinutes =
                Math.ceil(Number(current.estimatedMinutes) / 2 / 5) * 5;
            const secondMinutes =
                Number(current.estimatedMinutes) - firstMinutes;
            const nextDate =
                target.days.find((day) => day.date > after.dueDate)?.date ||
                after.dueDate;
            changes.push({
                after: [
                    { ...after, estimatedMinutes: firstMinutes },
                    {
                        ...after,
                        dueDate: nextDate,
                        estimatedMinutes: secondMinutes,
                        title: `${after.title} — Part 2`
                    }
                ],
                before: current,
                id: `split:${current.id}`,
                kind: "split",
                reason: `Split the missed ${current.subject} block across ${dayName(after.dueDate)} and ${dayName(nextDate)} to avoid overload.`,
                selected: true,
                taskId: current.id
            });
            return;
        }

        const moved = current.dueDate !== after.dueDate;
        const resized =
            Number(current.estimatedMinutes) !== after.estimatedMinutes;
        const replaced = current.title !== after.title;
        if (!moved && !resized && !replaced) return;
        const reason =
            current.dueDate < today
                ? `Moved ${current.subject} to ${dayName(after.dueDate)} because the original block was missed.`
                : moved
                  ? `Moved ${current.subject} to ${dayName(after.dueDate)} because the revised workload is lighter there.`
                  : resized
                    ? `${after.estimatedMinutes < current.estimatedMinutes ? "Shortened" : "Extended"} ${current.subject} to fit the updated weekly workload.`
                    : `Replaced the block because your current learning priorities changed.`;
        changes.push({
            after,
            before: current,
            id: `update:${current.id}`,
            kind: "update",
            reason,
            selected: true,
            taskId: current.id
        });
    });

    unmatched.forEach((task) => {
        changes.push({
            before: task,
            id: `delete:${task.id}`,
            kind: "delete",
            reason: `Removed ${task.title} because it is no longer among this week’s highest-priority study needs.`,
            selected: true,
            taskId: task.id
        });
    });

    return {
        changes,
        days: target.days,
        summary: target.summary
    };
}

export { THUTO_NOTE_PREFIX };

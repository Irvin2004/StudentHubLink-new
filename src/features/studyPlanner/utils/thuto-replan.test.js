import { expect, test } from "vitest";

import {
    detectThutoPlanAttention,
    generateThutoReplan
} from "./thuto-replan.js";

const now = new Date("2026-08-31T10:00:00");

test("detects missed blocks, early completion, and updated performance", () => {
    const result = detectThutoPlanAttention(
        {
            memoryTopics: [
                {
                    topic: "Calculus",
                    updatedAt: new Date("2026-08-30")
                }
            ],
            plannerTasks: [
                {
                    completed: false,
                    createdAt: new Date("2026-08-20"),
                    dueDate: "2026-08-29",
                    notes: "Generated by Thuto: review",
                    updatedAt: new Date("2026-08-20")
                },
                { completed: true, dueDate: "2026-09-03" }
            ]
        },
        now
    );

    expect(result.needsAttention).toBe(true);
    expect(result.reasons).toEqual(
        expect.arrayContaining([
            "A Thuto study block was missed.",
            "Finishing work early opened new study time.",
            "Your latest performance changed your learning priorities."
        ])
    );
});

test("proposes moving a missed generated block and adding new weak-topic work", () => {
    const result = generateThutoReplan(
        {
            availableMinutes: 180,
            memoryTopics: [
                {
                    id: "calculus",
                    latestQuizPercentage: 40,
                    level: "struggling",
                    topic: "Calculus"
                },
                { id: "chemistry", level: "struggling", topic: "Chemistry" }
            ],
            plannerTasks: [
                {
                    completed: false,
                    dueDate: "2026-08-29",
                    estimatedMinutes: 30,
                    id: "old-calculus",
                    notes: "Generated by Thuto: low score",
                    priority: "High",
                    subject: "Calculus",
                    taskType: "study",
                    title: "Review Calculus"
                }
            ]
        },
        now
    );

    expect(result.changes).toEqual(
        expect.arrayContaining([
            expect.objectContaining({ kind: "update", taskId: "old-calculus" }),
            expect.objectContaining({ kind: "add" })
        ])
    );
    expect(
        result.changes.find((change) => change.taskId === "old-calculus").reason
    ).toContain("because the original block was missed");
});

test("splits a long missed block across two days", () => {
    const result = generateThutoReplan(
        {
            availableMinutes: 180,
            memoryTopics: [
                { id: "chemistry", level: "struggling", topic: "Chemistry" }
            ],
            plannerTasks: [
                {
                    completed: false,
                    dueDate: "2026-08-28",
                    estimatedMinutes: 90,
                    id: "long-block",
                    notes: "Generated by Thuto: revision",
                    subject: "Chemistry",
                    title: "Review Chemistry"
                }
            ]
        },
        now
    );

    expect(result.changes[0]).toMatchObject({
        kind: "split",
        taskId: "long-block"
    });
    expect(result.changes[0].after).toHaveLength(2);
});
